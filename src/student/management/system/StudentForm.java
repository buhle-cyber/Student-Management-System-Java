    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        // When a user types "ABC123" this prevents the program from crashing
        int studentid;
        try {
        
        studentid = Integer.parseInt(txtStudentID.getText());
        } catch (NumberFormatException e) {
            
            JOptionPane.showMessageDialog(this, "Student ID must be a number.");
            
            return;
        }
        // Check for duplicate student ids
        for (int i = 0; i < model.getRowCount(); i++) {
            
            if(Integer.parseInt(model.getValueAt(i, 0).toString()) == studentid) {
                
                JOptionPane.showMessageDialog(this, "Student ID already exists");
                
                return;
            }
        }
        // Validate email
        if (!txtEmail.getText().contains("@")) {
            
            JOptionPane.showMessageDialog(this, "Please enter a valid email address.");
            
            return;
        }
        if (txtStudentID.getText().trim().isEmpty() ||
            txtFirstName.getText().trim().isEmpty() ||
            txtLastName.getText().trim().isEmpty() ||
            txtEmail.getText().trim().isEmpty()) {
            
            JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            // When validation fails, this will immediately stop the method
            return;
        }
        String firstName = txtFirstName.getText();
        String lastName = txtLastName.getText();
        String email = txtEmail.getText();
        String course = cmbCourse.getSelectedItem().toString();
        
        model.addRow(new Object[]
                {
                    studentid,
                    firstName,
                    lastName,
                    email,
                    course
                });
        // Save all students to the text file
        saveStudents();
    }//GEN-LAST:event_btnAddActionPerformed
