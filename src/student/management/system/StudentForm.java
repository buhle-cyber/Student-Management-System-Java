// DELETE BUTTON
    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        // Delete the selected row
        int row = tblStudent.getSelectedRow();
        // Clear the text fields
        if(row >= 0){
            lastDeletedStudent = new Object[model.getColumnCount()];
            
            for (int i = 0; i < model.getColumnCount(); i++) {
                lastDeletedStudent[i] = model.getValueAt(row, i);
            }
            
            lastDeletedRow = row;
            
            model.removeRow(row);
            
            saveStudents();
            
            ClearFields();
            
        } else {
            // Show a message if nothing is selected
            JOptionPane.showMessageDialog(this, "Please select a student to delete");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    // UPDATE BUTTON
    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        // Find the selected row
        int row = tblStudent.getSelectedRow();
        // Check if a row was selected
        if(row >= 0) {
            // Update 
            model.setValueAt(txtStudentID.getText(), row, 0);
            model.setValueAt(txtFirstName.getText(), row, 1);
            model.setValueAt(txtLastName.getText(), row, 2);
            model.setValueAt(txtEmail.getText(), row, 3);
            model.setValueAt(cmbCourse.getSelectedItem(), row, 4);
            
            // Display success message if studen is found
            JOptionPane.showMessageDialog(this, "Student updated successfully");
            saveStudents();
        } else {
            // If the student is not found display this message
            JOptionPane.showMessageDialog(this, "Please select a student to update.");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed
// SEARCH BUTTON
    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        // Getting text from the Student ID textbox
        String id = txtStudentID.getText();
        
        // Assumption that studenr doesn't exixt, however if they exist it will become true
        boolean found = false;
        // Looping through every row
        for(int i = 0; i < model.getRowCount(); i++) {
            // Comparing the Student IDs
            if(model.getValueAt(i,0).toString().equals(id)) {
                tblStudent.setRowSelectionInterval(i,i);
                // Filling in the textboxes
                txtFirstName.setText(model.getValueAt(i,1).toString());
                txtLastName.setText(model.getValueAt(i,2).toString());
                txtEmail.setText(model.getValueAt(i,3).toString());
                cmbCourse.setSelectedItem(model.getValueAt(i,4).toString());
                // Student is found
                found = true;
                // Stop searching
                break;
            }
        }
        // If student is not found display message
        if(!found) {
            JOptionPane.showMessageDialog(this, "Student not found");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUndoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUndoActionPerformed
        // TODO add your handling code here:
        // Check if there is something to undo
        if (lastDeletedStudent != null) {
            // Put the student back
            model.insertRow(lastDeletedRow, lastDeletedStudent);
            // Save the updated table
            saveStudents();
            
            JOptionPane.showMessageDialog(this, "Last deleted student restored.");
            
            // Clear the saved information
            lastDeletedStudent = null;
            lastDeletedRow = -1;
        } else {
            
            JOptionPane.showMessageDialog(this, "Nothing to undo");
        }
    }//GEN-LAST:event_btnUndoActionPerformed

